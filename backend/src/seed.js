// ── Seed function ─────────────────────────────────────────────────────────────

const PLAYER_SETS = [
  { name: "Marquee Set 1", order: 1, players: MARQUEE_SET_1 },
  { name: "Marquee Set 2", order: 2, players: MARQUEE_SET_2 },
  { name: "Set 3", order: 3, players: SET_3 },
  { name: "Set 4", order: 4, players: SET_4 },
  { name: "Set 5", order: 5, players: SET_5 },
  { name: "Set 6", order: 6, players: SET_6 },
];

const PLAYERS = PLAYER_SETS.flatMap(({ name, order, players }) =>
  players.map((player) => ({
    ...player,
    auctionSetName: name,
    auctionSetOrder: order,
  })),
);

async function seed() {
  await mongoose.connect(process.env.MONGO_URI);
  console.log("Connected to MongoDB");

  // Wipe existing data
  await Player.deleteMany({});
  await Team.deleteMany({});
  await AuctionSession.deleteMany({});
  console.log("Cleared existing players, teams and auction session");

  // Insert teams — use create() (not insertMany) so the pre-save hook
  // that initialises remainingPurse = purse is triggered for every document.
  const teams = await Team.create(TEAMS);
  console.log(`Inserted ${teams.length} teams`);

  // Insert players (all available, no team assigned yet)
  const players = await Player.insertMany(PLAYERS);
  console.log(`Inserted ${players.length} players`);

  console.log("\nSeed complete! You can now run the auction.");
  process.exit(0);
}

seed().catch((err) => {
  console.error("Seed failed:", err.message);
  process.exit(1);
});
